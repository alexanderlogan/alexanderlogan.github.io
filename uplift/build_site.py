#!/usr/bin/env python3
"""Build the Uplift page and the web runner's prompts from the project files.

Writes:
  index.html                  the page, with the real skills, interviews and reference outputs
  server/prompts.generated.js the same skills and interviews, imported by the live web runner

Run after editing anything in .claude/, CLAUDE.md, data/ or output/, so the page, the web
runner and Claude Code all use one playbook.
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent

def read(rel):
    return (ROOT / rel).read_text(encoding="utf-8")

interviews = [
    {"file": p.name, "text": p.read_text(encoding="utf-8")}
    for p in sorted((ROOT / "data" / "interviews").glob("*.md"))
]
system = [
    {"label": "CLAUDE.md", "kind": "Team context", "path": "CLAUDE.md"},
    {"label": "research-synthesis", "kind": "Skill", "path": ".claude/skills/research-synthesis/SKILL.md"},
    {"label": "prd-writer", "kind": "Skill", "path": ".claude/skills/prd-writer/SKILL.md"},
    {"label": "prd-critic", "kind": "Subagent", "path": ".claude/agents/prd-critic.md"},
    {"label": "story-writer", "kind": "Skill", "path": ".claude/skills/story-writer/SKILL.md"},
    {"label": "backlog-prioritizer", "kind": "Skill", "path": ".claude/skills/backlog-prioritizer/SKILL.md"},
    {"label": "/run-pipeline", "kind": "Command", "path": ".claude/commands/run-pipeline.md"},
]
for s in system:
    s["text"] = read(s["path"])
outputs = [
    {"label": "01 Research", "path": "output/01_research_synthesis.md"},
    {"label": "02 PRD", "path": "output/02_prd.md"},
    {"label": "03 Critic review", "path": "output/03_prd_review.md"},
    {"label": "04 Stories", "path": "output/04_user_stories.md"},
    {"label": "05 Backlog", "path": "output/05_backlog.md"},
]
for o in outputs:
    o["text"] = read(o["path"])

# Web runner prompts: the same files Claude Code reads.
skills = {n: read(f".claude/skills/{n}/SKILL.md") for n in
          ("research-synthesis", "prd-writer", "story-writer", "backlog-prioritizer")}
prompts = {"claudeMd": read("CLAUDE.md"), "skills": skills,
           "critic": read(".claude/agents/prd-critic.md"), "interviews": interviews}
(ROOT / "server" / "prompts.generated.js").write_text(
    "// Generated by build_site.py from CLAUDE.md, .claude/ and data/interviews/. Do not edit.\n"
    "export default " + json.dumps(prompts, indent=1, ensure_ascii=False) + ";\n",
    encoding="utf-8")

def cycle_time():
    """Stage timings of the reference run, from output/run_log.jsonl (written by scripts/runlog.py
    during /run-pipeline in Claude Code). None unless the log holds one complete run."""
    log = ROOT / "output" / "run_log.jsonl"
    if not log.exists():
        return None
    from datetime import datetime
    starts, stages, gate = {}, [], {}
    for line in log.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        e = json.loads(line)
        t = datetime.fromisoformat(e["t"])
        if e["event"] == "start":
            starts[e["stage"]] = t
        elif e["event"] == "end" and e["stage"] in starts:
            s = starts.pop(e["stage"])
            stages.append({"stage": e["stage"], "ms": int((t - s).total_seconds() * 1000), "end": t.timestamp()})
            if e["stage"] == "gate":
                gate = {k: e[k] for k in ("decision", "raised", "accepted") if k in e}
    by = {s["stage"]: s for s in stages}
    if not {"research", "gate", "backlog"} <= by.keys():
        return None
    t0 = by["research"]["end"] - by["research"]["ms"] / 1000
    return {"stages": [{"stage": s["stage"], "ms": s["ms"]} for s in stages],
            "toPrd": int((by["gate"]["end"] - t0) * 1000), "toBacklog": int((by["backlog"]["end"] - t0) * 1000),
            "gate": gate}

cycle = cycle_time()
print("reference run timings:", "from output/run_log.jsonl" if cycle else "none (no complete run log)")

data = json.dumps({"interviews": interviews, "system": system, "outputs": outputs, "cycle": cycle}).replace("</", "<\\/")
html = (ROOT / "template.html").read_text(encoding="utf-8").replace("/*__DATA__*/null", data)
(ROOT / "index.html").write_text(html, encoding="utf-8")
print("wrote", ROOT / "index.html", len(html), "bytes, and server/prompts.generated.js")
